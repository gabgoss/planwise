#!/usr/bin/env python3
"""The generated reference library and its generator.

references/00-Reference-Library.md is the one index of every on-demand
reference, and skills/planwise/SKILL.md cites it instead of listing them. It is
generated by tools/gen_reference_library.py from each reference's one-line
`consult-when:` frontmatter key, so these tests pin both halves of that
contract:

- every reference on the real tree carries the key, and the library on disk is
  byte-equal to an in-process render (the freshness guard: a reference edit
  cannot land without a regeneration);
- the generator folds `-Part-N-` files into one family row, refuses a reference
  with no key, detects a drifted key under `--check`, and writes CRLF whatever
  mix of line endings the references use;
- the library stays readable in one Read call (measure_files level OK).

Fixture trees live in pytest's tmp_path, never under plugins/planwise/.

Run with:  python -m pytest -q -c pytest.ini tests/test_reference_library.py
"""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "plugins" / "planwise" / "scripts"))
sys.path.insert(0, str(REPO / "tools"))

import gen_reference_library as gen
from measure_files import measure_file

LIBRARY = gen.DEFAULT_ROOT / "references" / gen.LIBRARY_NAME


def _write_reference(root: Path, name: str, consult_when: str | None, newline: str = "\n") -> Path:
    lines = ["---", f"description: fixture reference {name}"]
    if consult_when is not None:
        lines.append(f"consult-when: {consult_when}")
    lines += ["---", "", f"# {name}", "", "Body.", ""]
    path = root / "references" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(newline.join(lines).encode("utf-8"))
    return path


def _fixture_tree(root: Path) -> Path:
    _write_reference(root, "alpha.md", "Alpha base situation")
    _write_reference(root, "alpha-Part-3-Later.md", "Alpha part three")
    _write_reference(root, "alpha-Part-2-Middle.md", "Alpha part two")
    _write_reference(root, "beta-Part-2-Second.md", "Beta second part")
    _write_reference(root, "beta-Part-1-First.md", "Beta first part")
    _write_reference(root, "gamma.md", "Gamma situation, with a `a|b` pipe")
    return root


def _rows(text: str) -> list[str]:
    return [line for line in text.splitlines() if line.startswith("| [")]


# --- the real tree ---------------------------------------------------------


def test_every_reference_has_the_key():
    files = gen.reference_files(gen.DEFAULT_ROOT)
    assert files, "no references found -- path regression, not an empty tree"
    missing = [p.name for p in files if gen.read_consult_when(p) is None]
    assert missing == [], f"references with no one-line consult-when key: {missing}"


def test_in_process_render_equals_the_library_on_disk():
    assert LIBRARY.is_file(), f"missing {LIBRARY}"
    assert gen.library_bytes(gen.render_library()) == LIBRARY.read_bytes(), (
        f"{gen.LIBRARY_NAME} is stale -- run: python -B tools/gen_reference_library.py"
    )


def test_real_tree_has_one_row_per_family():
    files = gen.reference_files(gen.DEFAULT_ROOT)
    stems = {gen.family_stem(p.name)[0] for p in files}
    rows = _rows(gen.render_library())
    assert len(rows) == len(stems)
    for path in files:
        assert sum(f"]({path.name})" in row for row in rows) == 1, path.name


def test_rendered_library_measures_ok(tmp_path):
    rendered = tmp_path / gen.LIBRARY_NAME
    rendered.write_bytes(gen.library_bytes(gen.render_library()))
    result = measure_file(str(rendered))
    assert result["level"] == "OK", result
    assert result["tokens"] < 22_000, result


def test_check_passes_on_the_real_tree(capsys):
    assert gen.main(["--check"]) == 0
    assert "current" in capsys.readouterr().out


# --- the generator on fixture trees ----------------------------------------


def test_parts_fold_into_the_family_row(tmp_path):
    rows = _rows(gen.render_library(_fixture_tree(tmp_path)))
    assert len(rows) == 3
    alpha, beta, gamma = rows
    assert alpha == (
        "| [`alpha.md`](alpha.md), [`alpha-Part-2-Middle.md`](alpha-Part-2-Middle.md), "
        "[`alpha-Part-3-Later.md`](alpha-Part-3-Later.md) | Alpha base situation"
        "<br>[`alpha-Part-2-Middle.md`](alpha-Part-2-Middle.md): Alpha part two"
        "<br>[`alpha-Part-3-Later.md`](alpha-Part-3-Later.md): Alpha part three |"
    )
    # No base file: the lowest Part leads the row and its text comes first.
    assert beta.startswith("| [`beta-Part-1-First.md`](beta-Part-1-First.md), "
                           "[`beta-Part-2-Second.md`](beta-Part-2-Second.md) |")
    assert beta.endswith(
        "| Beta first part<br>[`beta-Part-2-Second.md`](beta-Part-2-Second.md): Beta second part |")
    assert gamma.endswith("| Gamma situation, with a `a\\|b` pipe |")


def test_a_base_and_two_parts_render_all_three_values_in_order(tmp_path):
    root = tmp_path
    _write_reference(root, "alpha.md", "Alpha base situation")
    _write_reference(root, "alpha-Part-3-Later.md", "Alpha part three")
    _write_reference(root, "alpha-Part-2-Middle.md", "Alpha part two")
    rows = _rows(gen.render_library(root))
    assert len(rows) == 1
    assert rows[0].endswith(
        "| Alpha base situation"
        "<br>[`alpha-Part-2-Middle.md`](alpha-Part-2-Middle.md): Alpha part two"
        "<br>[`alpha-Part-3-Later.md`](alpha-Part-3-Later.md): Alpha part three |"
    )


def test_a_family_with_no_base_leads_with_its_lowest_part(tmp_path):
    root = tmp_path
    _write_reference(root, "beta-Part-3-Third.md", "Beta third part")
    _write_reference(root, "beta-Part-1-First.md", "Beta first part")
    _write_reference(root, "beta-Part-2-Second.md", "Beta second part")
    rows = _rows(gen.render_library(root))
    assert len(rows) == 1
    assert rows[0].endswith(
        "| Beta first part"
        "<br>[`beta-Part-2-Second.md`](beta-Part-2-Second.md): Beta second part"
        "<br>[`beta-Part-3-Third.md`](beta-Part-3-Third.md): Beta third part |"
    )


def test_family_classification_uses_the_split_tool_regex():
    import split_reference

    assert gen.PART_FILE_RE is split_reference.PART_FILE_RE
    assert not hasattr(gen, "_PART_RE"), "the generator keeps no regex of its own"
    name = "alpha-Part-12-Topic.md"
    assert split_reference.PART_FILE_RE.match(name).group("stem") == "alpha"
    assert gen.family_stem(name) == ("alpha", 12)
    assert gen.family_stem("alpha.md") == ("alpha", 0)


def test_the_library_is_excluded_from_its_own_scan(tmp_path):
    root = _fixture_tree(tmp_path)
    assert gen.main(["--root", str(root)]) == 0
    assert gen.main(["--root", str(root), "--check"]) == 0
    assert all(gen.LIBRARY_NAME not in row for row in _rows(gen.render_library(root)))


def test_a_reference_without_the_key_is_refused(tmp_path, capsys):
    root = _fixture_tree(tmp_path)
    _write_reference(root, "delta.md", None)
    _write_reference(root, "epsilon.md", "")
    assert gen.main(["--root", str(root)]) == 1
    err = capsys.readouterr().err
    assert "delta.md" in err and "epsilon.md" in err
    assert not (root / "references" / gen.LIBRARY_NAME).exists(), "a refusal writes nothing"


def test_check_detects_a_drifted_key(tmp_path):
    root = _fixture_tree(tmp_path)
    assert gen.main(["--root", str(root)]) == 0
    assert gen.main(["--root", str(root), "--check"]) == 0
    _write_reference(root, "gamma.md", "Gamma situation, reworded")
    assert gen.main(["--root", str(root), "--check"]) == 1


def test_check_fails_when_the_library_is_missing(tmp_path):
    assert gen.main(["--root", str(_fixture_tree(tmp_path)), "--check"]) == 1


def test_library_is_crlf_over_a_mixed_tree(tmp_path):
    _write_reference(tmp_path, "lf-ref.md", "An LF reference", newline="\n")
    _write_reference(tmp_path, "crlf-ref.md", "A CRLF reference", newline="\r\n")
    assert gen.main(["--root", str(tmp_path)]) == 0
    data = (tmp_path / "references" / gen.LIBRARY_NAME).read_bytes()
    assert data.count(b"\n") > 0
    assert data.count(b"\r\n") == data.count(b"\n"), "every line ends in CRLF"
    text = data.decode("utf-8")
    assert "| An LF reference |" in text and "| A CRLF reference |" in text


def test_an_lf_library_on_disk_fails_check(tmp_path):
    root = _fixture_tree(tmp_path)
    library = root / "references" / gen.LIBRARY_NAME
    library.write_bytes(gen.render_library(root).encode("utf-8"))
    assert gen.main(["--root", str(root), "--check"]) == 1
